HO.lang = "en";

/* Look up a key; {name} style placeholders are filled from `vars`. */
HO.t = function (key, vars) {
  const row = HO.STR[key];
  let s = row ? (row[HO.lang] || row.en) : key;
  if (vars) for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
  return s;
};

/* Pick the current language out of a {en, am} pair written by a seller.
   Falls back to whichever one they actually wrote. */
HO.tt = function (pair) {
  if (pair == null) return "";
  if (typeof pair === "string") return pair;
  return pair[HO.lang] || pair.en || pair.am || "";
};

/* Re-label every static node carrying data-i18n / data-i18n-ph. */
HO.applyLang = function () {
  document.body.classList.toggle("lang-am", HO.lang === "am");
  document.documentElement.lang = HO.lang === "am" ? "am" : "en";
  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    el.textContent = HO.t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
    el.setAttribute("placeholder", HO.t(el.getAttribute("data-i18n-ph")));
  });
  document.querySelectorAll(".lang-btn").forEach(function (b) {
    b.classList.toggle("on", b.dataset.lang === HO.lang);
  });
};
